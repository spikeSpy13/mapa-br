import { test, expect } from '@playwright/test';
import { readFileSync, mkdirSync } from 'node:fs';
const output = process.env.MAPA_BR_EVIDENCE_DIR || '/tmp/mapa-br-neighborhoods';
mkdirSync(output, { recursive: true });

test('panorama nacional independe de qualquer arquivo municipal ou setorial', async ({ page }) => {
  const blocked: string[] = [];
  await page.route(/\/(municipios|setores|statistics\/uf)\//, route => { blocked.push(route.request().url()); return route.fulfill({ status: 404, body: '' }); });
  await page.goto('/');
  await expect(page.getByTestId('official-populacao')).toHaveText('203.080.756');
  await expect(page.getByTestId('official-domicilios')).toHaveText('90.704.582');
  await page.getByRole('button', { name: 'Sul', exact: true }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Sul');
  await expect(page.getByTestId('official-sources')).toContainText('Panorama nacional obtido diretamente');
  expect(blocked).toEqual([]);
  await page.getByRole('combobox', { name: 'Selecionar UF' }).selectOption('42');
  await expect(page.getByTestId('official-populacao')).toHaveText('7.610.361');
  await expect(page.getByTestId('official-domicilios')).toHaveText('3.475.161');
  await expect(page.getByText('Geometria municipal indisponível localmente.', { exact: false })).toBeVisible();
  await expect(page.getByTestId('official-map')).toHaveAttribute('data-layer', 'cd_uf');
  await page.unrouteAll();
  await page.route('**/geo/official/statistics/uf/42.json', r => r.fulfill({ status: 404, body: '' }));
  await page.reload();
  await expect(page.getByTestId('official-populacao')).toHaveText('7.610.361');
  await expect(page.getByTestId('official-map')).toHaveAttribute('data-layer', 'cd_mun');
  await expect(page.getByText('Indicadores municipais indisponíveis localmente.', { exact: false })).toBeVisible();
});

test('bairros declarados conservam todos os setores e reconciliam com o município', async ({ page }) => {
  const requests: string[] = [], errors: string[] = [];
  page.on('request', r => { if (r.url().includes('/geo/')) requests.push(r.url()); });
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/?level=municipio&cd_uf=42&cd_mun=4205407');
  const map = page.getByTestId('official-map');
  await expect(map).toHaveAttribute('data-ready', 'true');
  await expect(page.getByTestId('official-populacao')).toHaveText('537.211');
  await expect(page.getByTestId('official-domicilios')).toHaveText('285.000');
  const original = await map.locator('canvas').elementHandle();
  const details = page.getByTestId('official-neighborhoods');
  await details.locator('summary').click();
  const groups = details.locator('button[data-group-id]');
  await expect(groups).toHaveCount(88);
  await details.locator('[data-group-id="bairro:4205407001"]').click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Centro');
  await expect(page.getByTestId('official-populacao')).toHaveText('42.308');
  await expect(page.getByTestId('official-domicilios')).toHaveText('23.368');
  await expect(map).toHaveAttribute('data-feature-count', '1004');
  await expect(map).toHaveAttribute('data-ready', 'true');
  await expect(page.getByTestId('official-neighborhood-source')).toContainText('CD_BAIRRO');
  const groupRows = page.getByRole('region', { name: 'Lista de territórios' });
  await expect(groupRows.locator('button')).toHaveCount(88);
  const count = requests.length;
  await page.getByRole('combobox', { name: 'Colorir por' }).selectOption('domicilios');
  await expect(page.getByTestId('official-legend')).toContainText('Totais por agrupamento declarado');
  expect(requests).toHaveLength(count);
  await page.locator('.brand').hover();
  await page.screenshot({ path: `${output}/bairro-centro.png`, fullPage: true });
  await page.getByText('Setores deste agrupamento', { exact: true }).click();
  await page.getByRole('button', { name: 'Setor 420540705000001', exact: true }).click();
  await expect(page.getByTestId('official-populacao')).toHaveText('430');
  await expect(page.getByTestId('official-domicilios')).toHaveText('266');
  await page.goBack();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Centro');
  await expect(map).toHaveAttribute('data-ready', 'true');
  await groupRows.locator('[data-territory-id="sem_bairro:4205407"]').click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Setores sem bairro identificado');
  await expect(page.getByTestId('official-populacao')).toHaveText('17.748');
  await expect(page.getByTestId('official-domicilios')).toHaveText('8.817');
  await expect(page.getByText('Sem bairro identificado na fonte', { exact: false })).toBeVisible();
  await expect(map).toHaveAttribute('data-ready', 'true');
  await page.locator('.brand').hover();
  await page.screenshot({ path: `${output}/setores-sem-bairro.png`, fullPage: true });
  await page.getByRole('button', { name: /Voltar nível/ }).click();
  await expect(page.getByTestId('official-populacao')).toHaveText('537.211');
  await expect(page.getByRole('combobox', { name: 'Colorir por' })).toHaveValue('domicilios');
  expect(await original!.evaluate(c => c.isConnected)).toBe(true);
  expect(errors).toEqual([]);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/?level=bairro&cd_uf=42&cd_mun=4205407&id_agregacao=bairro%3A4205407001');
  await expect(page.getByTestId('official-populacao')).toHaveText('42.308');
  await expect(map).toHaveAttribute('data-ready', 'true');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `${output}/bairro-centro-celular.png`, fullPage: true });
  const data = JSON.parse(readFileSync('public/geo/official/statistics/municipios/42/4205407.json', 'utf8'));
  const ids = Object.values(data.bairros).flatMap((b: any) => b.cd_setores);
  expect(ids).toHaveLength(1004); expect(new Set(ids).size).toBe(1004);
});

