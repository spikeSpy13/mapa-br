  await expect(page.getByTestId('official-populacao')).toHaveText('42.308');
  await expect(map).toHaveAttribute('data-ready', 'true');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
