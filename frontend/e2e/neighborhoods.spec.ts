  await expect(page.getByTestId('official-legend')).toContainText('Cada setor tem seu próprio valor');
  expect(requests).toHaveLength(count);
  await page.locator('.brand').hover();
  await page.screenshot({ path: `${output}/bairro-centro.png`, fullPage: true });
  await list.locator('[data-territory-id="420540705000001"]').press('Enter');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Centro — Setor 420540705000001');
  await expect(page.getByTestId('sector-neighborhood')).toContainText('4205407001');
  await expect(page.getByTestId('official-populacao')).toHaveText('430');
  await expect(page.getByTestId('official-domicilios')).toHaveText('266');
  await expect(map).toHaveAttribute('data-ready', 'true');
  await page.screenshot({ path: `${output}/setor-com-bairro.png`, fullPage: true });
  await page.reload();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Centro — Setor 420540705000001');
  await page.getByRole('button', { name: /Voltar nível/ }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Centro');
  await page.getByRole('button', { name: /Voltar nível/ }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Florianópolis');
  await search.fill('não identificado');
  await expect(list.locator('[data-territory-id]')).toHaveCount(109);
  await list.getByRole('button', { name: 'Abrir bairro Bairro não identificado na fonte' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Bairro não identificado na fonte');
  await expect(page.getByTestId('official-populacao')).toHaveText('17.748');
